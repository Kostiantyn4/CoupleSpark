export type DeckId = 'regular' | 'intimate' | 'mixed';

export type Question = {
  id: string;
  text: string;
};

export type Deck = {
  id: DeckId;
  /** Назва табу */
  label: string;
  /** Категорія на картці */
  category: string;
  /** Підказка під питанням */
  hint: string;
  questions: Question[];
};

const q = (prefix: string, texts: string[]): Question[] =>
  texts.map((text, i) => ({ id: `${prefix}-${i + 1}`, text }));

